import Foundation
import CoreLocation

/// The local time zone of a place, offline: the IANA zone of that country whose main city is
/// closest to the given coordinate. Countries with one zone get that one; Brazil, the US,
/// Russia or Australia get the zone of the region the photos were taken in.
///
/// Used to split a trip's photos into days in the trip's own time, not the iPhone's current
/// one: evening photos in Rio, looked at from Belgium, would otherwise land on the next day.
enum TripTimeZone {
    /// The zone for a trip in `countryCode`, nearest to `latitude`/`longitude`. Nil for a
    /// country the table doesn't know (the caller falls back to the device's zone).
    static func zone(countryCode: String, latitude: Double, longitude: Double) -> TimeZone? {
        let code = countryCode.uppercased()
        let candidates = zones.filter { $0.country == code }
        guard !candidates.isEmpty else { return nil }
        let here = CLLocation(latitude: latitude, longitude: longitude)
        let nearest = candidates.min {
            here.distance(from: CLLocation(latitude: $0.latitude, longitude: $0.longitude))
                < here.distance(from: CLLocation(latitude: $1.latitude, longitude: $1.longitude))
        }
        return nearest.flatMap { TimeZone(identifier: $0.identifier) }
    }

    /// A Gregorian calendar in the trip's zone, or the device's calendar when unknown.
    static func calendar(countryCode: String, latitude: Double, longitude: Double) -> Calendar {
        var calendar = Calendar(identifier: .gregorian)
        calendar.timeZone = zone(countryCode: countryCode, latitude: latitude, longitude: longitude)
            ?? Calendar.current.timeZone
        return calendar
    }

    private struct Entry {
        let country: String
        let latitude: Double
        let longitude: Double
        let identifier: String
    }

